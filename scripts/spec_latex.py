#!/usr/bin/env python3
"""Verify or generate LaTeX and render every TLA+ module as inline documentation pages."""
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def generate_latex(source_text: str, jar: Path) -> str:
    """Run TLATeX in a temporary directory, retaining only its standalone LaTeX."""
    assert ' MODULE ' in source_text, 'TLATeX input must contain a module declaration'
    assert jar.is_file(), f'TLA tools jar missing: {jar}'
    with tempfile.TemporaryDirectory(prefix='overwatch-latex-') as directory:
        work = Path(directory)
        target = work / "Module.tla"
        target.write_text(source_text)
        result = subprocess.run(['java', '-cp', str(jar), 'tla2tex.TLA', '-number',
                                 '-textwidth', '500', '-hoffset', '-70', '-textheight', '680', '-voffset', '-60',
                                 '-latexCommand', 'pdflatex', '-latexOutputExt', 'pdf', target.name],
                                cwd=work, capture_output=True, text=True, timeout=90)
        if result.returncode or not target.with_suffix('.pdf').is_file():
            raise RuntimeError(f'TLATeX failed for {target.name}:\n{result.stdout}\n{result.stderr}')
        log = target.with_suffix('.log').read_text()
        if 'Overfull' in log:
            raise RuntimeError(f'{target.name} has overflowing typeset lines; wrap them in the TLA+ source')
        return '% Generated by scripts/spec_latex.py; edit the TLA+ source.\n' + target.with_suffix('.tex').read_text()


def render_latex_pages(text: str) -> list[str]:
    """Typeset generated LaTeX and convert every DVI page to a self-contained SVG."""
    assert '\\documentclass' in text, 'Expected standalone TLATeX output'
    assert '\\end{document}' in text, 'Generated LaTeX must be a complete document'
    with tempfile.TemporaryDirectory(prefix='overwatch-model-pages-') as directory:
        work = Path(directory)
        (work / 'Model.tex').write_text(text)
        subprocess.run(['latex', '-interaction=nonstopmode', '-halt-on-error', 'Model.tex'],
                       cwd=work, check=True, capture_output=True, timeout=90)
        subprocess.run(['dvisvgm', '--page=1-', '--no-fonts', '--exact-bbox',
                        '--output=page-%p.svg', 'Model.dvi'],
                       cwd=work, check=True, capture_output=True, timeout=90)
        pages = sorted(work.glob('page-*.svg'), key=lambda path: int(path.stem.split('-')[-1]))
        assert pages, 'dvisvgm produced no visible model pages'
        return [path.read_text() for path in pages]


def write_model_pages(pages: dict[str, str]) -> None:
    """Replace build-only page assets, removing pages that no longer exist in a model."""
    directory = ROOT / 'docs/assets/models'
    directory.mkdir(parents=True, exist_ok=True)
    assert pages, 'Refusing to publish an empty collection of model pages'
    assert all(name.endswith('.svg') and '/' not in name for name in pages), f'Invalid model assets: {pages.keys()}'
    for name, text in pages.items():
        (directory / name).write_text(text)
    for previous in directory.glob('*.svg'):
        if previous.name not in pages:
            previous.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--jar', type=Path, default=os.environ.get('TLA2TOOLS_JAR', str(Path.home() / '.cache/tlalings/tla2tools.jar')))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = sorted((ROOT / 'spec').glob('*.tla'))
    assert sources, 'No TLA+ modules found in spec/'
    assert len({source.stem for source in sources}) == len(sources), f'Module names must be unique: {sources}'
    pages = {}
    for source in sources:
        text = generate_latex(source.read_text(), args.jar.resolve())
        target = source.with_suffix('.tex')
        if args.check:
            if not target.is_file() or target.read_text() != text:
                raise SystemExit(f'{target.name} is stale; run python3 scripts/spec_latex.py')
        else:
            target.write_text(text)
        pages.update({f'{source.stem}-{index}.svg': svg for index, svg in enumerate(render_latex_pages(text), 1)})
    write_model_pages(pages)
    print(f'{len(pages)} inline model pages rendered')
    print(f'{len(sources)} generated LaTeX modules {"verified" if args.check else "written"}')


if __name__ == '__main__':
    main()
